import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { afterAll, describe, expect, it } from "vitest";
import { createSnapshot, updateSnapshot } from "../scripts/lib/snapshot.mjs";
import { README_TITLE, snapshotReadme } from "../scripts/lib/snapshot-readme.mjs";
import { walk } from "../scripts/lib/snapshot-guard.mjs";

const tmp = path.join(process.cwd(), ".test-tmp", "snapshot-readme");
fs.rmSync(tmp, { recursive: true, force: true });
afterAll(() => fs.rmSync(tmp, { recursive: true, force: true }));

const git = (cwd: string, ...a: string[]) => execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@invalid", ...a], { cwd, encoding: "utf8" }).trim();
const put = (root: string, rel: string, text: string) => {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};
const REF = "sell-a/alpha-1";

let counter = 0;
/** A tiny template repository (with its own README) and a content folder inside a git repository of its own. */
async function setup() {
  const base = path.join(tmp, `case-${++counter}`);
  const project = path.join(base, "project");
  const contentRoot = path.join(base, "content-repo");
  put(project, "package.json", JSON.stringify({ version: "9.9.9" }));
  put(project, "README.md", "# The template's own README\n");
  put(project, "examples/ex/e/product.json", "{}");
  put(project, "tests/fixtures/content/f/f/product.json", "{}");
  git(project, "init", "-q", "-b", "main");
  git(project, "add", "-A");
  git(project, "commit", "-q", "-m", "template");
  put(contentRoot, "sell-a/seller.json", JSON.stringify({ displayName: "sell-a" }));
  put(contentRoot, `${REF}/product.json`, JSON.stringify({ media: { hero: "a.jpg", gallery: [] } }));
  fs.mkdirSync(path.join(contentRoot, REF, "media"), { recursive: true });
  await sharp({ create: { width: 40, height: 30, channels: 3, background: "#888" } }).jpeg().toFile(path.join(contentRoot, REF, "media", "a.jpg"));
  put(contentRoot, ".gitignore", "media/\nmedia-web/\n"); // originals and exports are not in the content repository
  git(contentRoot, "init", "-q", "-b", "main");
  git(contentRoot, "add", "-A");
  git(contentRoot, "commit", "-q", "-m", "content");
  return { project, contentRoot, dest: path.join(base, "deploy") };
}

describe("the README of a deploy repository", () => {
  it("is generated instead of the template's README: same data as version.json, the exact regenerate command, no template text", async () => {
    const s = await setup();
    await createSnapshot({ projectRoot: s.project, contentRoot: s.contentRoot, product: REF, dest: s.dest });
    const readme = fs.readFileSync(path.join(s.dest, "README.md"), "utf8");
    const version = JSON.parse(fs.readFileSync(path.join(s.dest, "version.json"), "utf8"));
    expect(readme.startsWith(README_TITLE)).toBe(true);
    expect(readme).not.toContain("The template's own README");
    expect(readme).toContain("9.9.9");
    expect(readme).toContain(version.template);
    expect(readme).toContain(version.content);
    expect(readme).toContain(version.built);
    expect(readme).toContain(`npm run snapshot -- --product ${REF} --out <path to this folder> --update`);
    for (const name of ["LEADS_STORE", "TELEGRAM_BOT_TOKEN", "SITE_INDEXABLE", "CONTENT_PRODUCT"]) expect(readme).toContain(name);
    expect(git(s.dest, "ls-files", "README.md")).toBe("README.md");
  });

  it("holds no path of this machine and no value of a variable", async () => {
    const s = await setup();
    process.env.TELEGRAM_BOT_TOKEN = "123456789:abcdefghijklmnopqrstuvwxyzABCDEF";
    try {
      await createSnapshot({ projectRoot: s.project, contentRoot: s.contentRoot, product: REF, dest: s.dest });
    } finally {
      delete process.env.TELEGRAM_BOT_TOKEN;
    }
    const readme = fs.readFileSync(path.join(s.dest, "README.md"), "utf8");
    expect(readme).not.toContain(tmp);
    expect(readme).not.toContain("123456789:");
    expect(readme).not.toMatch(/@[a-z0-9-]+\.[a-z]/i); // no e-mail address
  });

  it("marks a source without a git repository as not recorded", () => {
    const readme = snapshotReadme({ ref: REF, info: { version: null, template: null, content: null, built: "2026-01-01 00:00" } });
    expect(readme).toContain("| Content commit | not recorded |");
  });

  it("is regenerated by --update without counting as a change, and a real change commits it along", async () => {
    const s = await setup();
    await createSnapshot({ projectRoot: s.project, contentRoot: s.contentRoot, product: REF, dest: s.dest });
    const before = git(s.dest, "rev-parse", "HEAD");
    const same = await updateSnapshot({ projectRoot: s.project, contentRoot: s.contentRoot, product: REF, dest: s.dest });
    expect(same.commit).toBeNull();
    expect(same.templateChanged).toEqual([]);
    expect(git(s.dest, "rev-parse", "HEAD")).toBe(before);
    expect(git(s.dest, "status", "--porcelain")).toBe("");

    put(s.contentRoot, `${REF}/product.json`, JSON.stringify({ media: { hero: "a.jpg", gallery: [], changed: true } }));
    git(s.contentRoot, "commit", "-aq", "-m", "edit");
    const changed = await updateSnapshot({ projectRoot: s.project, contentRoot: s.contentRoot, product: REF, dest: s.dest });
    expect(changed.changed).toEqual([`content/${REF}/product.json`]);
    expect(changed.templateChanged).toEqual([]);
    expect(git(s.dest, "show", "--name-only", "--format=", "HEAD").split("\n").sort()).toEqual(["README.md", `content/${REF}/product.json`, "version.json"].sort());
    expect(fs.readFileSync(path.join(s.dest, "README.md"), "utf8")).toContain(git(s.contentRoot, "rev-parse", "--short", "HEAD"));
    expect(walk(s.dest).some((f) => f.rel === "README.md")).toBe(true);
  });
});
